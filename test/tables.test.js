const { test } = require('node:test');
const assert = require('node:assert/strict');
const { tableState, tableMutation, tableForSale, releaseTable, productInOpenOrder } = require('../tables');

test('tables protect occupied visits, saved orders, and concurrent edits', () => {
  const data = { products: [{ id: 1, active: true, addons: [{ name: 'Cheese', price: 500 }] }] };
  assert.deepEqual(tableState(data), { restaurantEnabled: false, tables: [] });
  assert.equal(tableMutation(data, 'tables', 'POST', { name: '1', seats: 4 }).status, 409);
  assert.equal(tableMutation(data, 'restaurant', 'PUT', { enabled: true }).status, 200);
  assert.equal(tableMutation(data, 'tables', 'POST', { name: '1', seats: 0 }).status, 400);
  const table = tableMutation(data, 'tables', 'POST', { name: '1', seats: 4 }).value;
  assert.equal(tableMutation(data, 'tables', 'POST', { name: '1', seats: 4 }).status, 409);
  const patch = input => tableMutation(data, 'tables/1', 'PATCH', { version: table.version, ...input });
  assert.equal(patch({ action: 'open', guests: 5 }).status, 400);
  assert.equal(patch({ action: 'open', guests: 2 }).status, 200);
  assert.equal(tableMutation(data, 'restaurant', 'PUT', { enabled: false }).status, 409);
  assert.equal(tableMutation(data, 'tables/1', 'DELETE', {}).status, 409);
  assert.equal(patch({ action: 'details', name: '1', seats: 1 }).status, 409);
  assert.equal(patch({ action: 'order', items: [{ id: 1, quantity: 1, addons: [9] }] }).status, 409);
  const items = [{ id: 1, addons: [0], quantity: 2 }];
  assert.equal(patch({ action: 'order', items }).status, 200);
  assert.equal(productInOpenOrder(data, 1), true);
  assert.equal(patch({ action: 'close' }).status, 409);
  assert.equal(patch({ action: 'order', version: 1, items: [] }).status, 409);
  assert.equal(tableForSale(data, { tableId: 1, tableVersion: 1, items }).status, 409);
  assert.equal(tableForSale(data, { tableId: 1, tableVersion: table.version, items: [] }).status, 409);
  assert.equal(tableForSale(data, { tableId: 1, tableVersion: table.version, items }).table, table);
  releaseTable(table);
  assert.equal(table.openedAt, null);
  assert.deepEqual(table.order, []);
  assert.equal(productInOpenOrder(data, 1), false);
  assert.equal(tableMutation(data, 'tables/1', 'DELETE', {}).status, 200);
  assert.equal(tableState(data).tables.length, 0);
  assert.equal(tableMutation(data, 'restaurant', 'PUT', { enabled: false }).status, 200);
});

test('moving a table carries its order and guests, then allows the guest count to change', () => {
  const data = { restaurantEnabled: true, products: [{ id: 1, active: true, addons: [] }] };
  const source = tableMutation(data, 'tables', 'POST', { name: '1', seats: 4 }).value;
  const destination = tableMutation(data, 'tables', 'POST', { name: '2', seats: 3 }).value;
  const small = tableMutation(data, 'tables', 'POST', { name: '3', seats: 1 }).value;
  const patch = (table, input) => tableMutation(data, `tables/${table.id}`, 'PATCH', { version: table.version, ...input });
  assert.equal(patch(source, { action: 'open', guests: 2 }).status, 200);
  assert.equal(patch(source, { action: 'order', items: [{ id: 1, quantity: 2, addons: [] }] }).status, 200);
  assert.equal(patch(source, { action: 'move', destinationId: small.id, destinationVersion: small.version }).status, 409);
  assert.equal(patch(source, { action: 'move', destinationId: destination.id, destinationVersion: 0 }).status, 409);
  const openedAt = source.openedAt;
  const moved = patch(source, { action: 'move', destinationId: destination.id, destinationVersion: destination.version });
  assert.equal(moved.status, 200);
  assert.equal(moved.value.id, destination.id);
  assert.equal(source.openedAt, null);
  assert.deepEqual(source.order, []);
  assert.equal(destination.openedAt, openedAt);
  assert.deepEqual(destination.order, [{ id: 1, quantity: 2, addons: [] }]);
  assert.equal(destination.guests, 2);
  assert.equal(patch(source, { action: 'guests', guests: 1 }).status, 409);
  assert.equal(patch(destination, { action: 'guests', guests: 4 }).status, 400);
  assert.equal(patch(destination, { action: 'guests', guests: 3 }).status, 200);
  assert.equal(destination.guests, 3);
  assert.equal(tableForSale(data, { tableId: destination.id, tableVersion: destination.version, items: destination.order }).table, destination);
  assert.equal(patch(destination, { action: 'move', destinationId: source.id, destinationVersion: source.version }).status, 200);
  assert.equal(source.guests, 3);
});

test('combined tables share one order and release together without changing the floor', () => {
  const data = { restaurantEnabled: true, products: [{ id: 1, active: true, addons: [] }] };
  const add = (name, position) => tableMutation(data, 'tables', 'POST', { name, seats: 2, position });
  const first = add('A', 0).value;
  const second = add('B', 5).value;
  assert.equal(add('C', 5).status, 409);
  const patch = (table, input) => tableMutation(data, `tables/${table.id}`, 'PATCH', { version: table.version, ...input });
  const items = [{ id: 1, quantity: 2, addons: [] }];
  for (const table of [first, second]) {
    assert.equal(patch(table, { action: 'open', guests: 2 }).status, 200);
    assert.equal(patch(table, { action: 'order', items }).status, 200);
  }
  const combine = { action: 'combine', destinationId: second.id, destinationVersion: second.version };
  assert.equal(patch(first, { ...combine, destinationVersion: 1 }).status, 409);
  assert.equal(patch(first, combine).status, 200);
  assert.equal(first.guests, 4);
  assert.deepEqual(first.order, [{ id: 1, quantity: 4, addons: [] }]);
  assert.equal(patch(second, { action: 'open', guests: 1 }).status, 409);
  assert.equal(patch(first, { action: 'guests', guests: 3 }).status, 200);
  assert.equal(patch(first, { action: 'close' }).status, 409);
  const sale = tableForSale(data, { tableId: first.id, tableVersion: first.version, items: first.order });
  assert.equal(sale.table, first);
  releaseTable(sale.table);
  assert.equal(patch(second, { action: 'open', guests: 1 }).status, 200);
  assert.deepEqual(tableState(data).tables.map(table => table.position), [0, 5]);
});
