const { test } = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { Client } = require('pg');

test('sign-up, account settings, and register data are isolated', { skip: !process.env.POS_TEST_DATABASE_URL }, async () => {
  const schema = `pos_test_${crypto.randomBytes(8).toString('hex')}`;
  const client = new Client({ connectionString: process.env.POS_TEST_DATABASE_URL });
  await client.connect();
  try {
    await client.query(`CREATE SCHEMA ${schema}`);
    await client.query(`SET search_path TO ${schema}`);
    await client.query("CREATE SEQUENCE pos_account_ids; CREATE TABLE pos_credentials (id integer PRIMARY KEY DEFAULT nextval('pos_account_ids'), username text NOT NULL, password_hash text NOT NULL, promptpay_id text); CREATE UNIQUE INDEX username_unique ON pos_credentials (lower(username)); CREATE TABLE pos_state (id integer PRIMARY KEY, payload jsonb NOT NULL); CREATE TABLE pos_sessions (token_hash text PRIMARY KEY, expires_at timestamptz NOT NULL, account_id integer NOT NULL); CREATE TABLE pos_login_attempts (ip text PRIMARY KEY, attempts integer NOT NULL, reset_at timestamptz NOT NULL)");
    const url = new URL(process.env.POS_TEST_DATABASE_URL);
    url.searchParams.set('options', `-c search_path=${schema}`);
    process.env.DATABASE_URL = url.toString();
    const handler = require('../api/index');
    const call = async (route, method = 'GET', body, cookie = '') => {
      const headers = {};
      const res = { status(code) { this.code = code; }, setHeader(name, value) { headers[name] = value; }, json(data) { this.data = data; } };
      await handler({ method, query: { path: route }, body, headers: { host: 'test.invalid', cookie }, socket: { remoteAddress: '127.0.0.1' } }, res);
      return { status: res.code, data: res.data, cookie: headers['Set-Cookie']?.split(';')[0] };
    };
    assert.equal((await call('signup', 'POST', { username: 'bad', password: 'short' })).status, 400);
    const a = await call('signup', 'POST', { username: 'shop-a', password: 'test-password-123' });
    assert.equal(a.status, 201);
    const b = await call('signup', 'POST', { username: 'shop-b', password: 'test-password-456' });
    assert.equal(b.status, 201);
    assert.equal((await call('signup', 'POST', { username: 'SHOP-A', password: 'test-password-123' })).status, 409);
    assert.equal((await call('state')).status, 401);
    const empty = await call('state', 'GET', undefined, b.cookie);
    assert.deepEqual(empty.data.products, []);
    assert.deepEqual(empty.data.sales, []);
    assert.equal(empty.data.promptpayConfigured, false);
    const product = await call('products', 'POST', { name: 'Tea', price: 5000, addons: [] }, a.cookie);
    assert.equal(product.status, 201);
    assert.equal((await call('state', 'GET', undefined, a.cookie)).data.products[0].category, '');
    const categoryEdit = { name: 'Tea', price: 5000, addons: [], category: '  Drinks  ' };
    assert.equal((await call(`products/${product.data.id}`, 'PUT', categoryEdit, a.cookie)).status, 200);
    assert.equal((await call('state', 'GET', undefined, a.cookie)).data.products[0].category, 'Drinks');
    assert.equal((await call('products', 'POST', { ...categoryEdit, category: 123 }, a.cookie)).status, 400);
    assert.equal((await call(`products/${product.data.id}`, 'PUT', { ...categoryEdit, category: 'x'.repeat(61) }, a.cookie)).status, 400);
    assert.equal((await call(`products/${product.data.id}`, 'PUT', { ...categoryEdit, category: '' }, a.cookie)).status, 200);
    assert.equal((await call('state', 'GET', undefined, a.cookie)).data.products[0].category, '');
    assert.equal((await call(`products/${product.data.id}`, 'PUT', categoryEdit, a.cookie)).status, 200);

    assert.equal((await call(`products/${product.data.id}`, 'PATCH', { hidden: true }, b.cookie)).status, 404);
    assert.equal((await call('state', 'GET', undefined, b.cookie)).data.products.length, 0);
    const sale = { requestId: crypto.randomUUID(), payment: 'cash', received: 5000, items: [{ id: product.data.id, quantity: 1, addons: [] }] };
    assert.equal((await call('sales', 'POST', sale, a.cookie)).status, 201);
    assert.equal((await call('sales', 'POST', { ...sale, requestId: crypto.randomUUID() }, b.cookie)).status, 409);
    assert.equal((await call('state', 'GET', undefined, b.cookie)).data.sales.length, 0);
    assert.equal((await call('restaurant', 'PUT', { enabled: true }, a.cookie)).status, 200);
    const dining = await call('tables', 'POST', { name: '1', seats: 4 }, a.cookie);
    assert.equal(dining.status, 201);
    const opened = await call(`tables/${dining.data.id}`, 'PATCH', { action: 'open', guests: 2, version: dining.data.version }, a.cookie);
    assert.equal(opened.status, 200);
    const tableOrder = await call(`tables/${dining.data.id}`, 'PATCH', { action: 'order', items: sale.items, version: opened.data.version }, a.cookie);
    assert.equal(tableOrder.status, 200);
    const otherState = (await call('state', 'GET', undefined, b.cookie)).data;
    assert.equal(otherState.restaurantEnabled, false);
    assert.deepEqual(otherState.tables, []);
    assert.equal((await call(`tables/${dining.data.id}`, 'DELETE', {}, b.cookie)).status, 409);
    const tableSale = { ...sale, requestId: crypto.randomUUID(), tableId: dining.data.id, tableVersion: tableOrder.data.version };
    const paidTable = await call('sales', 'POST', tableSale, a.cookie);
    assert.equal(paidTable.status, 201);
    assert.equal((await call('sales', 'POST', tableSale, a.cookie)).data.id, paidTable.data.id);
    assert.equal((await call('state', 'GET', undefined, a.cookie)).data.tables[0].openedAt, null);
    assert.equal((await call('products/import', 'POST', { csv: 'name,price\nUnauthorized,10' })).status, 401);
    assert.equal((await call('products/import', 'POST', { csv: 'name,price\nWould be added,10\nInvalid,-1' }, a.cookie)).status, 400);
    assert.equal((await call('state', 'GET', undefined, a.cookie)).data.products.some(item => item.name === 'Would be added'), false);
    const importCsv = 'Product,Category,Price,Add-ons\nImported tea,Drinks,45,Cream cheese:10\nTEA,Drinks,99,';
    const imports = await Promise.all([call('products/import', 'POST', { csv: importCsv }, a.cookie), call('products/import', 'POST', { csv: importCsv }, a.cookie)]);
    assert.ok(imports.every(result => result.status === 200));
    assert.equal(imports.reduce((sum, result) => sum + result.data.added, 0), 1);
    const flexiblePrices = await call('products/import', 'POST', { csv: 'Product,Price\nBlank price,\nFormatted price,"฿1,000.005"' }, a.cookie);
    assert.equal(flexiblePrices.status, 200);
    const flexibleState = (await call('state', 'GET', undefined, a.cookie)).data;
    assert.equal(flexibleState.products.find(item => item.name === 'Blank price').price, 0);
    assert.equal(flexibleState.products.find(item => item.name === 'Formatted price').price, 100001);
    const importedItem = (await call('state', 'GET', undefined, a.cookie)).data.products.find(item => item.name === 'Imported tea');
    assert.equal(importedItem.price, 4500);
    assert.equal(importedItem.category, 'Drinks');
    assert.deepEqual(importedItem.addons, [{ name: 'Cream cheese', price: 1000 }]);
    assert.equal((await call('promotions', 'POST', { name: 'Empty categories', type: 'percent', value: 10, categories: [] }, a.cookie)).status, 400);
    assert.equal((await call('promotions', 'POST', { name: 'Missing category', type: 'percent', value: 10, categories: ['Missing'] }, a.cookie)).status, 400);
    const categoryPromo = await call('promotions', 'POST', { name: 'Drinks discount', type: 'percent', value: 10, categories: ['Drinks'] }, a.cookie);
    assert.equal(categoryPromo.status, 201);
    const futureDrink = await call('products', 'POST', { name: 'New drink', category: 'Drinks', price: 1000, addons: [] }, a.cookie);
    const dessert = await call('products', 'POST', { name: 'New dessert', category: 'Desserts', price: 2000, addons: [] }, a.cookie);
    const categoryOrder = { requestId: crypto.randomUUID(), payment: 'cash', received: 6950, promotionId: categoryPromo.data.id, items: [{ id: importedItem.id, quantity: 1, addons: [] }, { id: futureDrink.data.id, quantity: 1, addons: [] }, { id: dessert.data.id, quantity: 1, addons: [] }] };
    const categorySale = await call('sales', 'POST', categoryOrder, a.cookie);
    assert.equal(categorySale.status, 201);
    assert.equal(categorySale.data.total, 6950);
    assert.equal((await call('sales', 'POST', { ...categoryOrder, requestId: crypto.randomUUID(), items: [{ id: dessert.data.id, quantity: 1, addons: [] }] }, a.cookie)).status, 409);
    const categoryState = (await call('state', 'GET', undefined, a.cookie)).data;
    assert.deepEqual(categoryState.promotions.find(promo => promo.id === categoryPromo.data.id).categories, ['Drinks']);
    assert.deepEqual(categoryState.sales.find(sale => sale.id === categorySale.data.id).promotion.categories, ['Drinks']);
    assert.equal((await call(`promotions/${categoryPromo.data.id}`, 'PUT', { name: 'Desserts discount', type: 'fixed', value: 500, categories: ['Desserts'] }, a.cookie)).status, 200);

    assert.deepEqual((await call('state', 'GET', undefined, b.cookie)).data.products, []);
    assert.equal((await call('settings', 'PUT', { username: 'shop-a' }, b.cookie)).status, 409);
    assert.equal((await call('settings', 'GET', undefined, a.cookie)).data.username, 'shop-a');
    assert.equal((await call('settings', 'PUT', { promptpayId: 'invalid' }, a.cookie)).status, 400);
    assert.equal((await call('settings', 'PUT', { promptpayId: '0123456789' }, a.cookie)).status, 409);
    assert.equal((await call('settings', 'PUT', { manualPayments: ['Scan', 'EDC'] }, a.cookie)).status, 200);
    const manualSale = { requestId: crypto.randomUUID(), payment: 'manual:Scan', items: [{ id: product.data.id, quantity: 1, addons: [] }] };
    assert.equal((await call('sales', 'POST', manualSale, a.cookie)).status, 201);
    assert.equal((await call('settings', 'PUT', { manualPayments: ['Card', 'EDC'] }, a.cookie)).status, 200);
    assert.equal((await call('sales', 'POST', { ...manualSale, requestId: crypto.randomUUID() }, a.cookie)).status, 409);
    assert.equal((await call('state', 'GET', undefined, a.cookie)).data.sales.some(sale => sale.payment === 'manual:Scan'), true);
    assert.deepEqual((await call('state', 'GET', undefined, b.cookie)).data.manualPayments, ['Scan', 'EDC']);
    assert.equal((await call('settings', 'PUT', { promptpayEnabled: true }, a.cookie)).status, 200);
    assert.equal((await call('settings', 'PUT', { promptpayId: '0123456789' }, a.cookie)).status, 200);
    assert.equal((await call('state', 'GET', undefined, a.cookie)).data.promptpayConfigured, true);
    assert.equal((await call('state', 'GET', undefined, b.cookie)).data.promptpayConfigured, false);
    assert.equal((await call('settings', 'PUT', { currentPassword: 'wrong', newPassword: 'changed-password-123' }, a.cookie)).status, 403);
    assert.equal((await call('settings', 'PUT', { currentPassword: 'test-password-123', newPassword: 'changed-password-123' }, a.cookie)).status, 200);
    assert.equal((await call('state', 'GET', undefined, b.cookie)).status, 200);
    assert.equal((await call('login', 'POST', { username: 'shop-a', password: 'test-password-123' })).status, 401);
    assert.equal((await call('login', 'POST', { username: 'SHOP-A', password: 'changed-password-123' })).status, 200);
    assert.equal((await call('logout', 'POST', {}, b.cookie)).status, 200);
    assert.equal((await call('state', 'GET', undefined, b.cookie)).status, 401);
  } finally {
    await client.query(`DROP SCHEMA ${schema} CASCADE`);
    await client.end();
  }
});
