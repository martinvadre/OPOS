const { test } = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const os = require('node:os');
const fs = require('node:fs');
const path = require('node:path');

test('add-ons, promotions, hidden products, and sales persist without double counting', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pos-test-'));
  const port = 31000 + Math.floor(Math.random() * 20000);
  const cwd = path.join(__dirname, '..');
  const setup = spawn(process.execPath, ['server.js', '--set-password'], { cwd, env: { ...process.env, POS_DATA_DIR: dir }, stdio: ['pipe', 'ignore', 'inherit'] });
  setup.stdin.end('test-password-123');
  await new Promise((resolve, reject) => setup.on('exit', code => code === 0 ? resolve() : reject(new Error('Password setup failed'))));
  fs.writeFileSync(path.join(dir, 'promptpay-id.txt'), '0123456789\n', { mode: 0o600 });
  const child = spawn(process.execPath, ['server.js'], { cwd, env: { ...process.env, POS_DATA_DIR: dir, PORT: String(port) }, stdio: 'ignore' });
  const base = `http://127.0.0.1:${port}`;
  try {
    for (let i = 0; i < 100; i++) {
      try { await fetch(base); break; } catch { await new Promise(resolve => setTimeout(resolve, 20)); }
    }
    let cookie;
    const call = async (route, method = 'GET', payload) => {
      const response = await fetch(`${base}/api/${route}`, { method, headers: { 'Content-Type': 'application/json', ...(cookie ? { Cookie: cookie } : {}) }, body: payload && JSON.stringify(payload) });
      if (response.headers.get('set-cookie')) cookie = response.headers.get('set-cookie').split(';')[0];
      return { status: response.status, data: await response.json() };
    };
    assert.equal((await call('state')).status, 401);
    assert.equal((await call('login', 'POST', { username: 'admin', password: 'test-password-123' })).status, 200);
    assert.equal((await call('settings')).data.username, 'admin');
    assert.equal((await call('settings', 'PUT', { username: 'shop.owner', currentPassword: 'wrong', newPassword: 'changed-password-123' })).status, 403);
    assert.equal((await call('settings', 'PUT', { username: 'shop.owner', currentPassword: 'test-password-123', newPassword: 'changed-password-123' })).status, 200);
    assert.equal((await call('logout', 'POST')).status, 200);
    assert.equal((await call('login', 'POST', { username: 'admin', password: 'test-password-123' })).status, 401);
    assert.equal((await call('login', 'POST', { username: 'shop.owner', password: 'changed-password-123' })).status, 200);
    const product = await call('products', 'POST', { name: 'Tea', price: 250, addons: [{ name: 'Cream cheese', price: 1000 }] });
    assert.equal(product.status, 201);
    assert.equal((await call('state')).data.products[0].category, '');
    const categoryEdit = { name: 'Tea', price: 250, addons: [{ name: 'Cream cheese', price: 1000 }], category: '  Drinks  ' };
    assert.equal((await call(`products/${product.data.id}`, 'PUT', categoryEdit)).status, 200);
    assert.equal((await call('state')).data.products[0].category, 'Drinks');
    assert.equal((await call('products', 'POST', { ...categoryEdit, category: 123 })).status, 400);
    assert.equal((await call(`products/${product.data.id}`, 'PUT', { ...categoryEdit, category: 'x'.repeat(61) })).status, 400);
    assert.equal((await call(`products/${product.data.id}`, 'PUT', { ...categoryEdit, category: '' })).status, 200);
    assert.equal((await call('state')).data.products[0].category, '');
    assert.equal((await call(`products/${product.data.id}`, 'PUT', categoryEdit)).status, 200);
    const qr = await call('promptpay?amount=500');
    assert.equal(qr.status, 200);
    assert.match(qr.data.qr, /^data:image\/png;base64,/);
    assert.notEqual((await call('promptpay?amount=600')).data.qr, qr.data.qr);
    assert.equal((await call('promptpay?amount=0')).status, 400);
    assert.equal((await call('sales', 'POST', { requestId: crypto.randomUUID(), payment: 'card', items: [{ id: product.data.id, quantity: 1 }] })).status, 400);
    assert.equal((await call('promotions', 'POST', { name: 'Too much', type: 'percent', value: 101 })).status, 400);
    assert.equal((await call('promotions', 'POST', { name: 'Duplicate types', effects: [{ type: 'fixed', value: 100 }, { type: 'fixed', value: 200 }] })).status, 400);
    const promotion = await call('promotions', 'POST', { name: 'Tea special', type: 'fixed', value: 100 });
    assert.equal(promotion.status, 201);
    assert.equal((await call('state')).data.promotions[0].name, 'Tea special');
    const order = { requestId: crypto.randomUUID(), payment: 'cash', received: 2400, promotionId: promotion.data.id, items: [{ id: product.data.id, quantity: 2, addons: [0] }] };
    const first = await call('sales', 'POST', order);
    assert.equal(first.data.total, 2400);
    assert.equal((await call('sales', 'POST', order)).data.id, first.data.id);
    assert.equal((await call('state')).data.products[0].addons[0].name, 'Cream cheese');
    assert.equal((await call('products/' + product.data.id, 'PATCH', { hidden: true })).status, 200);
    assert.equal((await call('sales', 'POST', { ...order, requestId: crypto.randomUUID() })).status, 409);
    assert.equal((await call('products/' + product.data.id, 'PATCH', { hidden: false })).status, 200);
    const saved = JSON.parse(fs.readFileSync(path.join(dir, 'pos-data.json'), 'utf8'));
    assert.equal(saved.products[0].hidden, false);
    assert.equal(saved.products[0].category, 'Drinks');
    assert.equal(saved.sales.length, 1);
    assert.equal(saved.sales[0].subtotal, 2500);
    assert.equal(saved.sales[0].items[0].addons[0].name, 'Cream cheese');
    assert.equal(saved.sales[0].discount, 100);
    assert.equal(saved.sales[0].promotion.name, 'Tea special');
    assert.equal((await call('promotions/' + promotion.data.id, 'PUT', { name: 'Invalid edit', effects: [{ type: 'fixed', value: 0 }] })).status, 400);
    assert.equal((await call('promotions/' + promotion.data.id, 'PUT', { name: 'Tea special updated', effects: [{ type: 'fixed', value: 200 }], productIds: [product.data.id] })).status, 200);
    assert.equal((await call('state')).data.promotions[0].name, 'Tea special updated');
    assert.equal((await call('state')).data.sales.find(sale => sale.id === first.data.id).promotion.name, 'Tea special');
    assert.equal((await call('sales', 'POST', { requestId: crypto.randomUUID(), payment: 'cash', received: 1050, promotionId: promotion.data.id, items: [{ id: product.data.id, quantity: 1, addons: [0] }] })).data.total, 1050);
    assert.equal((await call('promotions/' + promotion.data.id, 'PATCH', { hidden: true })).status, 200);
    assert.equal((await call('state')).data.promotions[0].hidden, true);
    assert.equal((await call('sales', 'POST', { requestId: crypto.randomUUID(), payment: 'cash', received: 1050, promotionId: promotion.data.id, items: [{ id: product.data.id, quantity: 1, addons: [0] }] })).status, 409);
    assert.equal((await call('promotions/' + promotion.data.id, 'PATCH', { hidden: false })).status, 200);
    assert.equal((await call('sales', 'POST', { ...order, requestId: crypto.randomUUID(), discount: -1 })).status, 400);
    assert.equal((await call('promotions/' + promotion.data.id, 'DELETE')).status, 200);
    assert.equal((await call('state')).data.promotions.length, 0);
    assert.equal((await call('sales', 'POST', { ...order, requestId: crypto.randomUUID() })).status, 409);
    assert.equal(fs.statSync(path.join(dir, 'credentials.json')).mode & 0o777, 0o600);
    const second = await call('products', 'POST', { name: 'Coffee', price: 300, addons: [] });
    assert.equal((await call('promotions', 'POST', { name: 'Invalid scope', type: 'fixed', value: 100, productIds: [9999] })).status, 400);
    assert.equal((await call('promotions', 'POST', { name: 'Empty scope', type: 'fixed', value: 100, productIds: [] })).status, 400);
    const scoped = await call('promotions', 'POST', { name: 'Tea only', type: 'percent', value: 10, productIds: [product.data.id] });
    assert.equal(scoped.status, 201);
    const scopedSale = await call('sales', 'POST', { requestId: crypto.randomUUID(), payment: 'cash', received: 1425, promotionId: scoped.data.id, items: [{ id: product.data.id, quantity: 1, addons: [0] }, { id: second.data.id, quantity: 1, addons: [] }] });
    assert.equal(scopedSale.status, 201);
    assert.equal(scopedSale.data.total, 1425);
    assert.equal((await call('sales', 'POST', { requestId: crypto.randomUUID(), payment: 'cash', received: 300, promotionId: scoped.data.id, items: [{ id: second.data.id, quantity: 1, addons: [] }] })).status, 409);
    assert.equal((await call('promotions', 'POST', { name: 'Missing add-on', effects: [{ type: 'free_addon', addonName: 'Whipped cream' }], productIds: [product.data.id] })).status, 400);
    const free = await call('promotions', 'POST', { name: 'Free cream cheese', effects: [{ type: 'free_addon', addonName: 'Cream cheese' }], productIds: [product.data.id] });
    assert.equal(free.status, 201);
    assert.equal((await call('sales', 'POST', { requestId: crypto.randomUUID(), payment: 'cash', received: 250, promotionId: free.data.id, items: [{ id: product.data.id, quantity: 1, addons: [0] }] })).data.total, 250);
    assert.equal((await call('sales', 'POST', { requestId: crypto.randomUUID(), payment: 'cash', received: 1500, promotionId: free.data.id, items: [{ id: product.data.id, quantity: 2, addons: [0] }] })).data.total, 1500);
    assert.equal((await call('sales', 'POST', { requestId: crypto.randomUUID(), payment: 'cash', received: 250, promotionId: free.data.id, items: [{ id: product.data.id, quantity: 1, addons: [] }] })).status, 409);
    const combined = await call('promotions', 'POST', { name: 'Free cream cheese and ten percent', effects: [{ type: 'free_addon', addonName: 'Cream cheese' }, { type: 'percent', value: 10 }], productIds: [product.data.id] });
    assert.equal(combined.status, 201);
    const combinedSale = await call('sales', 'POST', { requestId: crypto.randomUUID(), payment: 'cash', received: 525, promotionId: combined.data.id, items: [{ id: product.data.id, quantity: 1, addons: [0] }, { id: second.data.id, quantity: 1, addons: [] }] });
    assert.equal(combinedSale.status, 201);
    assert.equal(combinedSale.data.total, 525);
    const percent = await call('promotions', 'POST', { name: 'Ten percent', type: 'percent', value: 10 });
    assert.ok(percent.data.id > promotion.data.id);
    const percentSale = await call('sales', 'POST', { requestId: crypto.randomUUID(), payment: 'promptpay', promotionId: percent.data.id, items: [{ id: second.data.id, quantity: 1, addons: [] }] });
    assert.equal(percentSale.status, 201);
    assert.equal(percentSale.data.total, 270);
    assert.equal((await call('state')).data.sales[0].payment, 'promptpay');
    assert.equal((await call('restaurant', 'PUT', { enabled: true })).status, 200);
    const dining = await call('tables', 'POST', { name: 'Table 1', seats: 4 });
    assert.equal(dining.status, 201);
    const opened = await call(`tables/${dining.data.id}`, 'PATCH', { action: 'open', guests: 2, version: dining.data.version });
    assert.equal(opened.status, 200);
    const tableItems = [{ id: second.data.id, addons: [], quantity: 2 }];
    const savedOrder = await call(`tables/${dining.data.id}`, 'PATCH', { action: 'order', items: tableItems, version: opened.data.version });
    assert.equal(savedOrder.status, 200);
    assert.equal((await call(`tables/${dining.data.id}`, 'PATCH', { action: 'order', items: [], version: opened.data.version })).status, 409);
    assert.equal((await call(`products/${second.data.id}`, 'PATCH', { hidden: true })).status, 409);
    assert.equal((await call('restaurant', 'PUT', { enabled: false })).status, 409);
    const tableSale = { requestId: crypto.randomUUID(), payment: 'cash', received: 600, items: tableItems, tableId: dining.data.id, tableVersion: savedOrder.data.version };
    assert.equal((await call('sales', 'POST', { ...tableSale, received: 0 })).status, 409);
    assert.ok((await call('state')).data.tables[0].openedAt);
    const paid = await call('sales', 'POST', tableSale);
    assert.equal(paid.status, 201);
    assert.equal(paid.data.total, 600);
    assert.equal((await call('sales', 'POST', tableSale)).data.id, paid.data.id);
    const afterCheckout = (await call('state')).data;
    assert.equal(afterCheckout.tables[0].openedAt, null);
    assert.deepEqual(afterCheckout.tables[0].order, []);
    assert.equal(afterCheckout.sales[0].table.name, 'Table 1');
    assert.equal(afterCheckout.sales[0].table.guests, 2);
    assert.equal((await call('restaurant', 'PUT', { enabled: false })).status, 200);
    const importCsv = 'Product,Category,Price,Add-ons\nImported tea,Drinks,45,Cream cheese:10\nTEA,Drinks,99,\nImported tea,Drinks,50,';
    assert.equal((await call('products/import', 'POST', { csv: 'name,price\nWould be added,10\nInvalid,-1' })).status, 400);
    assert.equal((await call('state')).data.products.some(item => item.name === 'Would be added'), false);
    const imported = await call('products/import', 'POST', { csv: importCsv });
    assert.equal(imported.status, 200);
    assert.deepEqual(imported.data, { added: 1, skipped: 2 });
    assert.deepEqual((await call('products/import', 'POST', { csv: importCsv })).data, { added: 0, skipped: 3 });
    const flexiblePrices = await call('products/import', 'POST', { csv: 'Product,Price\nBlank price,\nFormatted price,"฿1,000.005"' });
    assert.equal(flexiblePrices.status, 200);
    const flexibleState = (await call('state', 'GET', undefined)).data;
    assert.equal(flexibleState.products.find(item => item.name === 'Blank price').price, 0);
    assert.equal(flexibleState.products.find(item => item.name === 'Formatted price').price, 100001);
    const importedItem = (await call('state')).data.products.find(item => item.name === 'Imported tea');
    assert.equal(importedItem.price, 4500);
    assert.equal(importedItem.category, 'Drinks');
    assert.deepEqual(importedItem.addons, [{ name: 'Cream cheese', price: 1000 }]);
    assert.equal((await call('promotions', 'POST', { name: 'Empty categories', type: 'percent', value: 10, categories: [] })).status, 400);
    assert.equal((await call('promotions', 'POST', { name: 'Missing category', type: 'percent', value: 10, categories: ['Missing'] })).status, 400);
    const categoryPromo = await call('promotions', 'POST', { name: 'Drinks discount', type: 'percent', value: 10, categories: ['Drinks'] });
    assert.equal(categoryPromo.status, 201);
    const futureDrink = await call('products', 'POST', { name: 'New drink', category: 'Drinks', price: 1000, addons: [] });
    const dessert = await call('products', 'POST', { name: 'New dessert', category: 'Desserts', price: 2000, addons: [] });
    const categoryOrder = { requestId: crypto.randomUUID(), payment: 'cash', received: 6950, promotionId: categoryPromo.data.id, items: [{ id: importedItem.id, quantity: 1, addons: [] }, { id: futureDrink.data.id, quantity: 1, addons: [] }, { id: dessert.data.id, quantity: 1, addons: [] }] };
    const categorySale = await call('sales', 'POST', categoryOrder);
    assert.equal(categorySale.status, 201);
    assert.equal(categorySale.data.total, 6950);
    assert.equal((await call('sales', 'POST', { ...categoryOrder, requestId: crypto.randomUUID(), items: [{ id: dessert.data.id, quantity: 1, addons: [] }] })).status, 409);
    const categoryState = (await call('state', 'GET', undefined)).data;
    assert.deepEqual(categoryState.promotions.find(promo => promo.id === categoryPromo.data.id).categories, ['Drinks']);
    assert.deepEqual(categoryState.sales.find(sale => sale.id === categorySale.data.id).promotion.categories, ['Drinks']);
    assert.equal((await call(`promotions/${categoryPromo.data.id}`, 'PUT', { name: 'Desserts discount', type: 'fixed', value: 500, categories: ['Desserts'] })).status, 200);

    assert.equal((await call('settings')).data.promptpayEnabled, true);
    assert.deepEqual((await call('settings')).data.manualPayments, ['Scan', 'EDC']);
    assert.equal((await call('settings', 'PUT', { manualPayments: ['Scan', 'scan'] })).status, 400);
    assert.equal((await call('settings', 'PUT', { manualPayments: ['Cash'] })).status, 400);
    assert.equal((await call('settings', 'PUT', { promptpayEnabled: false })).status, 200);
    assert.equal((await call('promptpay?amount=500')).status, 409);
    const manualOrder = { requestId: crypto.randomUUID(), payment: 'manual:Scan', items: [{ id: second.data.id, quantity: 1, addons: [] }] };
    assert.equal((await call('sales', 'POST', { ...manualOrder, payment: 'promptpay' })).status, 409);
    const manualSale = await call('sales', 'POST', manualOrder);
    assert.equal(manualSale.status, 201);
    assert.equal((await call('settings', 'PUT', { manualPayments: ['Card', 'EDC'] })).status, 200);
    assert.equal((await call('sales', 'POST', manualOrder)).status, 200);
    assert.equal((await call('sales', 'POST', { ...manualOrder, requestId: crypto.randomUUID() })).status, 409);
    assert.equal((await call('sales', 'POST', { ...manualOrder, requestId: crypto.randomUUID(), payment: 'manual:Card' })).status, 201);
    assert.deepEqual((await call('state')).data.manualPayments, ['Card', 'EDC']);
    assert.equal((await call('state')).data.sales.find(sale => sale.id === manualSale.data.id).payment, 'manual:Scan');
    assert.equal((await call('settings', 'PUT', { promptpayId: '0123456789' })).status, 409);
    assert.equal((await call('settings', 'PUT', { promptpayEnabled: true })).status, 200);
    assert.equal((await call('promptpay?amount=500')).status, 200);

    assert.equal(JSON.parse(fs.readFileSync(path.join(dir, 'pos-data.json'), 'utf8')).products.some(item => item.id === importedItem.id), true);
  } finally {
    child.kill();
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
